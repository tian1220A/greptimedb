/// A bound parameter value for a parameterized SQL statement.
///
/// Values live here and never in the SQL text, so the remote driver can bind
/// them natively (no literal quoting / injection). Structure and values are
/// kept apart: see [`crate::source::QueryRep`].
#[derive(Debug, Clone, PartialEq)]
pub enum SqlParam {
    Bool(bool),
    Int8(i8),
    Int16(i16),
    Int32(i32),
    Int64(i64),
    UInt8(u8),
    UInt16(u16),
    UInt32(u32),
    UInt64(u64),
    Float32(f32),
    Float64(f64),
    String(String),
}
